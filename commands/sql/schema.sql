CREATE TABLE IF NOT EXISTS customer (
    customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_type varchar(20) NOT NULL CHECK (customer_type IN ('individual', 'business')),
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    phone varchar(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS employee (
    employee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('admin', 'manager', 'director', 'guest')),
    login varchar(100) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS car (
    car_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customer(customer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    vin varchar(17) NOT NULL UNIQUE,
    license_plate varchar(20) NOT NULL UNIQUE,
    model varchar(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS service (
    service_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(160) NOT NULL UNIQUE,
    price numeric(12, 2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS part (
    part_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(160) NOT NULL,
    article varchar(80) NOT NULL UNIQUE,
    price numeric(12, 2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS orders (
    order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id integer NOT NULL REFERENCES car(car_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    employee_id integer NOT NULL REFERENCES employee(employee_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    order_date date NOT NULL DEFAULT CURRENT_DATE,
    deadline date,
    status varchar(40) NOT NULL,
    discount numeric(5, 2) NOT NULL DEFAULT 0 CHECK (discount >= 0 AND discount <= 100),
    total_cost numeric(12, 2) NOT NULL DEFAULT 0 CHECK (total_cost >= 0),
    mileage integer NOT NULL CHECK (mileage >= 0),
    CHECK (deadline IS NULL OR deadline >= order_date)
);

CREATE TABLE IF NOT EXISTS order_service (
    order_id integer NOT NULL REFERENCES orders(order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    service_id integer NOT NULL REFERENCES service(service_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    employee_id integer NOT NULL REFERENCES employee(employee_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    PRIMARY KEY (order_id, service_id)
);

CREATE TABLE IF NOT EXISTS order_part (
    order_id integer NOT NULL REFERENCES orders(order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    part_id integer NOT NULL REFERENCES part(part_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity integer NOT NULL CHECK (quantity > 0),
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    PRIMARY KEY (order_id, part_id)
);

CREATE INDEX IF NOT EXISTS ix_car_customer_id ON car(customer_id);
CREATE INDEX IF NOT EXISTS ix_orders_car_id ON orders(car_id);
CREATE INDEX IF NOT EXISTS ix_orders_employee_id ON orders(employee_id);
CREATE INDEX IF NOT EXISTS ix_orders_order_date ON orders(order_date);
CREATE INDEX IF NOT EXISTS ix_order_service_service_id ON order_service(service_id);
CREATE INDEX IF NOT EXISTS ix_order_service_employee_id ON order_service(employee_id);
CREATE INDEX IF NOT EXISTS ix_order_part_part_id ON order_part(part_id);
